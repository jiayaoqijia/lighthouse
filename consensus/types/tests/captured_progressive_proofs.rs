use flate2::read::GzDecoder;
use merkle_proof::verify_merkle_proof;
use serde::Deserialize;
use ssz::Encode;
use std::{collections::BTreeMap, io::Read};
use tree_hash::TreeHash;
use types::{BeaconState, EthSpec, ForkName, Hash256, MainnetEthSpec};

#[derive(Deserialize)]
struct Proof {
    gindex: usize,
    leaf: Hash256,
    branch: Vec<Hash256>,
}
#[derive(Deserialize)]
struct Vectors {
    slot: u64,
    state_root: Hash256,
    validators: usize,
    builders: usize,
    proofs: BTreeMap<String, Proof>,
}

/// Actual common 384-validator state from two Lighthouse BNs and patched Lodestar.
/// Expected roots and complete branches are generated by the unchanged selected
/// Python consensus specification, rather than by the Rust methods under test.
#[test]
fn captured_nondefault_gloas_state_and_three_proofs_match_independent_reference() {
    let vectors: Vectors =
        serde_json::from_slice(include_bytes!("../testdata/gloas-384-proofs.json")).unwrap();
    let mut bytes = vec![];
    GzDecoder::new(include_bytes!("../testdata/gloas-384-state.ssz.gz").as_slice())
        .read_to_end(&mut bytes)
        .unwrap();
    let spec = ForkName::Gloas.make_genesis_spec(MainnetEthSpec::default_spec());
    let mut state = BeaconState::<MainnetEthSpec>::from_ssz_bytes(&bytes, &spec).unwrap();
    assert_eq!(state.fork_name_unchecked(), ForkName::Gloas);
    assert_eq!(state.slot().as_u64(), vectors.slot);
    assert_eq!(state.validators().len(), vectors.validators);
    assert_eq!(state.builders().unwrap().len(), vectors.builders);
    assert_eq!(state.canonical_root().unwrap(), vectors.state_root);
    assert_eq!(state.as_ssz_bytes(), bytes);
    let cases = [
        (
            "current_sync_committee",
            2945,
            state.current_sync_committee().unwrap().tree_hash_root(),
            state.compute_current_sync_committee_proof().unwrap(),
        ),
        (
            "next_sync_committee",
            2946,
            state.next_sync_committee().unwrap().tree_hash_root(),
            state.compute_next_sync_committee_proof().unwrap(),
        ),
        (
            "finalized_root",
            735,
            state.finalized_checkpoint().root,
            state.compute_finalized_root_proof().unwrap(),
        ),
    ];
    for (name, index, leaf, branch) in cases {
        let expected = &vectors.proofs[name];
        assert_eq!(expected.gindex, index, "{name}");
        assert_eq!(expected.leaf, leaf, "{name}");
        assert_eq!(expected.branch, branch, "{name}");
        let depth = index.ilog2() as usize;
        let position = index - (1 << depth);
        assert!(
            verify_merkle_proof(leaf, &branch, depth, position, vectors.state_root),
            "{name}"
        );
        let mask = Hash256::from([1u8; 32]);
        assert!(
            !verify_merkle_proof(leaf ^ mask, &branch, depth, position, vectors.state_root),
            "changed leaf {name}"
        );
        let mut altered = branch.clone();
        altered[0] = altered[0] ^ mask;
        assert!(
            !verify_merkle_proof(leaf, &altered, depth, position, vectors.state_root),
            "changed sibling {name}"
        );
        assert!(
            !verify_merkle_proof(leaf, &branch, depth, position ^ 1, vectors.state_root),
            "changed index {name}"
        );
    }
}
